#!/usr/bin/env node
/**
 * Assembles a unified Docker Compose / Dokploy environment template
 * (.env.compose.example) from individual app contracts:
 *   - apps/api/.env.example
 *   - apps/app/.env.example
 *   - apps/web/.env.example
 *
 * Can also run in read-only check mode:
 *   node scripts/generate-compose-env.mjs --check
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "..")

const API_EXAMPLE = path.join(ROOT, "apps", "api", ".env.example")
const APP_EXAMPLE = path.join(ROOT, "apps", "app", ".env.example")
const WEB_EXAMPLE = path.join(ROOT, "apps", "web", ".env.example")
const OUTPUT_FILE = path.join(ROOT, ".env.compose.example")

function readSection(filePath, serviceName, description) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing expected source file: ${filePath}`)
  }
  const content = fs.readFileSync(filePath, "utf-8").trim()
  return [
    `# ------------------------------------------------------------------------------`,
    `# [${serviceName}] ${description}`,
    `# Source: ${path.relative(ROOT, filePath).replace(/\\/g, "/")}`,
    `# ------------------------------------------------------------------------------`,
    content,
  ].join("\n")
}

function generate() {
  const header = [
    `# ==============================================================================`,
    `# DOCKER COMPOSE / DOKPLOY UNIFIED ENVIRONMENT TEMPLATE`,
    `#`,
    `# Auto-generated from individual app contracts (apps/*/.env.example).`,
    `# DO NOT EDIT THIS FILE DIRECTLY.`,
    `# Edit the respective app's .env.example and run: pnpm env:compose`,
    `# ==============================================================================`,
    ``,
  ].join("\n")

  const sections = [
    readSection(API_EXAMPLE, "apps/api", "Backend Core, Secrets & Config (Passed to 'api' service)"),
    readSection(APP_EXAMPLE, "apps/app", "Vite SPA (Passed as build args to 'app' service)"),
    readSection(WEB_EXAMPLE, "apps/web", "Marketing SSR (Passed to 'web' service)"),
  ]

  return `${header}${sections.join("\n\n")}\n`
}

const isCheck = process.argv.includes("--check")
const generated = generate()

if (isCheck) {
  if (!fs.existsSync(OUTPUT_FILE)) {
    console.error(`❌ .env.compose.example does not exist. Run "pnpm env:compose" to create it.`)
    process.exit(1)
  }
  const current = fs.readFileSync(OUTPUT_FILE, "utf-8")
  if (current !== generated) {
    console.error(`❌ .env.compose.example is out of date with apps/*/.env.example. Run "pnpm env:compose" to update.`)
    process.exit(1)
  }
  console.log("✔ .env.compose.example is up to date.")
} else {
  fs.writeFileSync(OUTPUT_FILE, generated, "utf-8")
  console.log(`✔ Generated: ${OUTPUT_FILE}`)
}
